function level = blankLevel()
%BLANKLEVEL Level record with the canonical field order and empty bodies.
    config = pendulum.defaultConfig();
    level = struct();
    level.meta = struct( ...
        'seed', uint32(0), ...
        'levelIndex', 1, ...
        'generatorVersion', config.generatorVersion, ...
        'physicsVersion', config.physicsVersion, ...
        'difficultyVersion', config.difficultyVersion, ...
        'hash', "", ...
        'worldHash', "", ...
        'verified', false);
    level.title = "";
    level.stageTitle = "";
    level.bounds = [-8 50 -12 22];
    level.physics = pendulum.physicsBlock(config);
    level.start = struct('position', [1 config.playerRadius], ...
        'velocity', [config.runSpeed 0], 'mode', "GROUNDED");
    level.goal = struct('rect', [0 0 1 1], 'direction', "any");
    level.camera = struct('viewWidth', config.viewWidth, 'anchorFraction', config.anchorFraction);
    level.anchors = repmat(pendulum.makeAnchor(0, [0 0]), 0, 1);
    level.platforms = repmat(pendulum.makePlatform(0, [0 0 0 0], true), 0, 1);
    level.hazards = repmat(pendulum.makeHazard(0, "gear", "circle", [0 0], 0, [0 0 0 0]), 0, 1);
    level.collectibles = repmat(pendulum.makeCollectible(0, [0 0]), 0, 1);
    level.decorations = repmat(pendulum.makeDecoration(0, "arch", [0 0], [1 1], 0), 0, 1);
    level.witness = struct( ...
        'actions', zeros(0, 1, 'uint8'), ...
        'events', repmat(struct('tick', 0, 'type', ""), 0, 1), ...
        'finalTick', 0, ...
        'clearance', 1e6, ...
        'integratorId', config.integratorId, ...
        'checksum', "");
end
