function physics = physicsBlock(config)
%PHYSICSBLOCK Physics constants stored on a level so its hash covers them.
    physics = struct( ...
        'dt', config.dt, ...
        'gravity', config.gravity, ...
        'playerRadius', config.playerRadius, ...
        'acquireRange', config.acquireRange, ...
        'minRopeLength', config.minRopeLength, ...
        'winchSpeed', config.winchSpeed, ...
        'landingSpeed', config.landingSpeed, ...
        'runSpeed', config.runSpeed, ...
        'integratorId', string(config.integratorId));
end
